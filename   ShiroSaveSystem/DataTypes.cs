using System;

[Serializable]
public struct IntSaveData
{
    public string key;
    public int defaultValue;
}

[Serializable]
public struct FloatSaveData
{
    public string key;
    public float defaultValue;
}

[Serializable]
public struct BoolSaveData
{
    public string key;
    public bool defaultValue;
}

[Serializable]
public struct StringSaveData
{
    public string key;
    public String defaultValue;
}

